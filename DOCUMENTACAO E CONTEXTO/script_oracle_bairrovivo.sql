CREATE OR REPLACE PACKAGE PKG_COMUNIDADE AS
    PROCEDURE PR_REGISTRAR_ATUALIZACAO(
        p_id_ocorrencia IN NUMBER,
        p_id_usuario    IN NUMBER,
        p_tipo          IN VARCHAR2,
        p_comentario    IN VARCHAR2 DEFAULT NULL,
        p_url_foto      IN VARCHAR2 DEFAULT NULL
    );

    FUNCTION FN_TOTAL_VOTOS_ATIVOS(
        p_id_ocorrencia IN NUMBER
    ) RETURN NUMBER;
END PKG_COMUNIDADE;
/

CREATE OR REPLACE PACKAGE BODY PKG_COMUNIDADE AS
    PROCEDURE PR_REGISTRAR_ATUALIZACAO(
        p_id_ocorrencia IN NUMBER,
        p_id_usuario    IN NUMBER,
        p_tipo          IN VARCHAR2,
        p_comentario    IN VARCHAR2 DEFAULT NULL,
        p_url_foto      IN VARCHAR2 DEFAULT NULL
    ) IS
        v_confirmacoes NUMBER;
    BEGIN
        INSERT INTO TB_ATUALIZACAO_OCORRENCIA (
            ID_OCORRENCIA, ID_USUARIO, TIPO, COMENTARIO, URL_FOTO_EVIDENCIA, CRIADA_EM
        ) VALUES (
            p_id_ocorrencia, p_id_usuario, UPPER(TRIM(p_tipo)), p_comentario, p_url_foto, CURRENT_TIMESTAMP
        );

        IF UPPER(TRIM(p_tipo)) = 'CONFIRMACAO' THEN
            UPDATE TB_OCORRENCIA
               SET CONFIRMACOES  = CONFIRMACOES + 1,
                   ATUALIZADA_EM = CURRENT_TIMESTAMP
             WHERE ID_OCORRENCIA = p_id_ocorrencia
         RETURNING CONFIRMACOES INTO v_confirmacoes;

            IF v_confirmacoes >= 3 THEN
                UPDATE TB_OCORRENCIA
                   SET VALIDADA_COMUNIDADE = 'S',
                       URGENCIA = CASE WHEN URGENCIA IN ('BAIXA', 'MEDIA') THEN 'ALTA' ELSE URGENCIA END
                 WHERE ID_OCORRENCIA = p_id_ocorrencia;
            END IF;
        END IF;

        COMMIT;
    END PR_REGISTRAR_ATUALIZACAO;

    FUNCTION FN_TOTAL_VOTOS_ATIVOS(
        p_id_ocorrencia IN NUMBER
    ) RETURN NUMBER IS
        v_total NUMBER := 0;
    BEGIN
        SELECT COUNT(*)
          INTO v_total
          FROM TB_ATUALIZACAO_OCORRENCIA
         WHERE ID_OCORRENCIA = p_id_ocorrencia
           AND TIPO = 'CONFIRMACAO';
        RETURN v_total;
    END FN_TOTAL_VOTOS_ATIVOS;
END PKG_COMUNIDADE;
